import numpy as np
import pytest

from ezpit import processing as proc


def test_warn_once(monkeypatch):
    # Patch the print function to capture output
    printed_messages = []

    def mock_print(msg):
        printed_messages.append(msg)

    monkeypatch.setattr("builtins.print", mock_print)
    proc.reset_warning_history()  # Start from a clean state

    # First call emits a RuntimeWarning and prints; the second (same message) is
    # suppressed, so nothing new is warned or printed.
    with pytest.warns(RuntimeWarning, match="This is a warning."):
        proc._warn_once("This is a warning.")
    proc._warn_once("This is a warning.")

    assert printed_messages == ["[Warning] This is a warning."]

    proc.reset_warning_history()  # Reset the warning history for other tests
    with pytest.warns(RuntimeWarning, match="This is a warning."):
        proc._warn_once("This is a warning.")
    assert len(printed_messages) == 2  # Now it should print again


@pytest.mark.parametrize(
    ("qmin", "qmax", "sq"),
    [
        (0.0, 4.0, [1.0, 1.0, 1.0, 1.0]),  # S(q) == 1 -> F(q) == 0 everywhere
        (0.0, 4.0, [2.0, 2.0, 2.0, 2.0]),  # S(q) - 1 == 1 -> F(q) == Q
        (1.0, 5.0, [0.0, 1.0, 2.0, 3.0]),  # mixed, non-zero qmin
        (0.5, 10.0, [1.5, 0.5, 2.0, 1.0, 3.0]),  # odd length
    ],
)
def test_cal_fq_matches_formula(qmin, qmax, sq):
    sq_arr = np.asarray(sq, dtype=float)
    expected_q = np.linspace(qmin, qmax, len(sq_arr), endpoint=False)
    expected_fq = (sq_arr - 1.0) * expected_q

    fq, q_range = proc.cal_fq(qmin, qmax, sq_arr)

    assert q_range.shape == sq_arr.shape
    assert fq.shape == sq_arr.shape
    # The Q-axis starts at qmin and excludes qmax (endpoint=False).
    assert q_range[0] == pytest.approx(qmin)
    assert q_range[-1] < qmax
    np.testing.assert_allclose(q_range, expected_q)
    np.testing.assert_allclose(fq, expected_fq)


def test_load_atom_name_positions_basic(tmp_path):
    xyz = tmp_path / "mol.xyz"
    xyz.write_text(
        "3\ntitle / comment line, not an atom\nC 0.0 0.0 0.0\nO 1.0 2.0 3.0\nH -1.5 0.25 4.0\n",
        encoding="utf-8",
    )

    names, positions = proc.load_atom_name_positions(xyz, ["C", "O", "H"])

    assert names == ["C", "O", "H"]
    assert positions.shape == (3, 3)
    np.testing.assert_allclose(
        positions,
        [[0.0, 0.0, 0.0], [1.0, 2.0, 3.0], [-1.5, 0.25, 4.0]],
    )


def test_load_atom_name_positions_skips_headers_and_extra_columns(tmp_path):
    # Count line, blank lines, provenance/energy headers, and trailing columns
    # (charge/force) must all be ignored.
    xyz = tmp_path / "messy.xyz"
    xyz.write_text(
        "2\nenergy = -123.45\n\ngenerated by some tool\nC 0.0 0.0 0.0 0.5 extra\nO 1.0 1.0 1.0 -0.5\n",
        encoding="utf-8",
    )

    names, positions = proc.load_atom_name_positions(xyz, ["C", "O"])

    assert names == ["C", "O"]
    assert positions.shape == (2, 3)


