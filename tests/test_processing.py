def test_smooth_like_savitzky_golay_uses_converted_lambda():
    y = np.sin(np.linspace(0.0, 2.0 * np.pi, 50))
    bandwidth, order = 5.0, 2
    expected = proc.smooth_whittaker(y, proc.bandwidth_to_lambda(bandwidth, order), order)
    np.testing.assert_allclose(proc.smooth_like_savitzky_golay(y, bandwidth, order), expected)


def test_smooth_with_noise_gain_uses_converted_lambda():
    y = np.sin(np.linspace(0.0, 2.0 * np.pi, 50))
    gain, order = 1e-3, 2
    expected = proc.smooth_whittaker(y, proc.noise_gain_to_lambda(gain, order), order)
    np.testing.assert_allclose(proc.smooth_with_noise_gain(y, gain=gain, order=order), expected)


def test_batch_smooth_whittaker_matches_per_row():
    rng = np.random.default_rng(1)
    y_2d = rng.standard_normal((3, 40))
    out = proc.batch_smooth_whittaker(y_2d, lambda_=100.0, order=2)

    assert out.shape == y_2d.shape
    for i in range(y_2d.shape[0]):
        np.testing.assert_allclose(out[i], proc.smooth_whittaker(y_2d[i], 100.0, 2))
